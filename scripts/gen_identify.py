#!/usr/bin/env python3
"""Generate rtl/nvme_identify.sv: Identify Controller / Namespace data as SystemVerilog
functions returning one DW (little-endian bytes) for a DW index 0..1023.

Edit the constants below (serial number, model, firmware, NQN) and re-run:
    python3 scripts/gen_identify.py > rtl/nvme_identify.sv
"""
import struct

SN    = "ZC706RAMDISK0001"
MN    = "ZC706 NVMe RAM Disk"
FR    = "0.1"
NQN   = "nqn.2026-11.io.zc706:ramdisk"
VID   = 0x10EE
SSVID = 0x10EE
OUI   = 0x000A35          # IEEE OUI (Xilinx)
MDTS  = 5                 # 2^5 * 4 KB = 128 KB
VER   = 0x00020400        # NVMe 2.4
NQ    = 4                 # I/O queue pairs (informational only)


def ascii_field(s, n):
    b = s.encode("ascii")[:n]
    return b + b" " * (n - len(b))


def put(buf, off, data):
    buf[off:off + len(data)] = data


def ident_ctrl():
    b = bytearray(4096)
    put(b, 0, struct.pack("<HH", VID, SSVID))
    put(b, 4, ascii_field(SN, 20))
    put(b, 24, ascii_field(MN, 40))
    put(b, 64, ascii_field(FR, 8))
    b[72] = 0                                   # RAB
    put(b, 73, struct.pack("<I", OUI)[:3])      # IEEE OUI
    b[76] = 0                                   # CMIC
    b[77] = MDTS
    put(b, 78, struct.pack("<H", 1))            # CNTLID
    put(b, 80, struct.pack("<I", VER))          # VER
    b[111] = 1                                  # CNTRLTYPE: I/O controller
    put(b, 256, struct.pack("<H", 0))           # OACS
    b[258] = 3                                  # ACL (0's based)
    b[259] = 3                                  # AERL (0's based)
    b[260] = 0x02                               # FRMW: 1 slot
    b[261] = 0                                  # LPA
    b[262] = 0                                  # ELPE
    b[263] = 0                                  # NPSS (1 power state)
    put(b, 266, struct.pack("<H", 343))         # WCTEMP 343 K
    put(b, 268, struct.pack("<H", 373))         # CCTEMP 373 K
    b[512] = 0x66                               # SQES
    b[513] = 0x44                               # CQES
    put(b, 516, struct.pack("<I", 1))           # NN
    put(b, 520, struct.pack("<H", 0))           # ONCS
    b[525] = 0                                  # VWC: no volatile write cache
    put(b, 536, struct.pack("<I", 0))           # SGLS: not supported
    put(b, 768, NQN.encode("ascii"))            # SUBNQN (NUL padded)
    put(b, 2048, struct.pack("<H", 2500))       # PSD0 MP = 25.00 W
    return b


def ident_ns_static():
    b = bytearray(4096)
    # NSZE / NCAP / NUSE (bytes 0..23) are filled from a parameter in RTL
    b[25] = 0                                   # NLBAF (1 format)
    b[26] = 0                                   # FLBAS
    put(b, 128, struct.pack("<I", 12 << 16))    # LBAF0: LBADS = 12 (4096 B)
    return b


def dws(b):
    return [struct.unpack_from("<I", b, i * 4)[0] for i in range(1024)]


def emit_func(name, words, extra_args="", pre_cases=""):
    out = []
    out.append(f"  function automatic logic [31:0] {name}(input logic [9:0] idx{extra_args});")
    out.append("    case (idx)")
    if pre_cases:
        out.append(pre_cases)
    for i, w in enumerate(words):
        if w != 0:
            out.append(f"      10'd{i}: return 32'h{w:08X};")
    out.append("      default: return 32'h00000000;")
    out.append("    endcase")
    out.append("  endfunction")
    return "\n".join(out)


def main():
    c = dws(ident_ctrl())
    n = dws(ident_ns_static())
    nsze = ("      10'd0, 10'd2, 10'd4: return nsze[31:0];\n"
            "      10'd1, 10'd3, 10'd5: return nsze[63:32];")
    print("// nvme_identify.sv - GENERATED by scripts/gen_identify.py, do not edit by hand")
    print("package nvme_identify;")
    print()
    print(emit_func("id_ctrl_dw", c))
    print()
    print(emit_func("id_ns_dw", n, extra_args=", input logic [63:0] nsze", pre_cases=nsze))
    print()
    print("endpackage")


if __name__ == "__main__":
    main()
